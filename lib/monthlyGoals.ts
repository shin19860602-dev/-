export function monthlyGoal(amount: number): number {
  return Math.ceil(Math.max(0, amount) * 110 / 100);
}

// 日本時間の日付ごとに、店舗別にシャッフルしたコメントを巡回する。
export function dailyEncouragement(now: Date, storeId: string): string {
  const p = jstParts(now);
  const day = Math.floor(Date.UTC(p.year, p.month, p.date) / 86400000);

  let seed = [...storeId].reduce((hash, char) => (hash * 31 + char.charCodeAt(0)) >>> 0, 0);
  const shuffled = [...encouragements];
  for (let i = shuffled.length - 1; i > 0; i--) {
    seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0;
    const j = seed % (i + 1);
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }
  return shuffled[((day % shuffled.length) + shuffled.length) % shuffled.length];
}
